# 市场 -> agent 数据目录
MARKET_DIRS = {
    "us": "data/agent_data",
    "cn": "data/agent_data_astock",
    "hk": "data/agent_data_hk",
}


def main():
    for market, dates in REASONING.items():
        base = ROOT / MARKET_DIRS[market] / "deepseek-v4-flash" / "log"
        for date, content in dates.items():
            log_file = base / date / "log.jsonl"
            log_file.parent.mkdir(parents=True, exist_ok=True)
            existing = ""
            if log_file.exists():
                existing = log_file.read_text(encoding="utf-8")
            if '"role": "assistant"' in existing:
                print(f"  [skip] {market} {date} 已有 assistant 消息")
                continue
            line = json.dumps(
                {"signature": "deepseek-v4-flash",
                 "new_messages": [{"role": "assistant", "content": content}]},
                ensure_ascii=False,
            )
            with open(log_file, "a", encoding="utf-8") as f:
                f.write(line + "\n")
            print(f"  [ok] {market} {date} -> {log_file}")


if __name__ == "__main__":
    main()
